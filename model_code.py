import mlflow
import pandas as pd
from sklearn.pipeline import Pipeline
from xgboost import XGBRegressor
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
import pickle
import logging
from prometheus_client import Counter, Histogram
import uuid
from datetime import datetime

# MLflow setup for experiment tracking
mlflow.set_experiment("real_estate_pricing")

# Production ML Pipeline
class RealEstateMLSystem:
    def __init__(self):
        self.pipeline = None
        self.metrics = {}
        self.logger = logging.getLogger(__name__)

    def create_preprocessor(self):
        # Placeholder for a preprocessor. In a real system, this would be a more complex component.
        # For now, let's assume direct feature input for demonstration.
        from sklearn.preprocessing import StandardScaler
        from sklearn.compose import ColumnTransformer
        from sklearn.preprocessing import OneHotEncoder

        numeric_features = ['area', 'bedrooms', 'bathrooms', 'age', 'floor']
        categorical_features = ['location', 'property_type', 'facing']

        preprocessor = ColumnTransformer(
            transformers=[
                ('num', StandardScaler(), numeric_features),
                ('cat', OneHotEncoder(handle_unknown='ignore'), categorical_features)
            ], remainder='passthrough')
        return preprocessor

    def build_pipeline(self):
        """Build complete ML pipeline"""
        self.pipeline = Pipeline([
            ('preprocessor', self.create_preprocessor()),
            ('model', XGBRegressor(
                n_estimators=200,
                learning_rate=0.1,
                max_depth=6,
                random_state=42
            ))
        ])

    def train_with_tracking(self, X_train, y_train, X_val, y_val):
        """Train model with comprehensive tracking"""
        with mlflow.start_run():
            # Log parameters
            mlflow.log_params(self.pipeline.named_steps['model'].get_params())

            # Train model
            self.pipeline.fit(X_train, y_train)

            # Evaluate
            train_pred = self.pipeline.predict(X_train)
            val_pred = self.pipeline.predict(X_val)

            # Calculate metrics
            from sklearn.metrics import mean_absolute_error, r2_score
            train_mae = mean_absolute_error(y_train, train_pred)
            val_mae = mean_absolute_error(y_val, val_pred)
            val_r2 = r2_score(y_val, val_pred)

            # Log metrics
            mlflow.log_metrics({
                'train_mae': train_mae,
                'val_mae': val_mae,
                'val_r2': val_r2
            })

            # Log model
            mlflow.sklearn.log_model(self.pipeline, "model")

            self.logger.info(f"Training complete. Validation MAE: ₹{val_mae:,.2f}, R²: {val_r2:.3f}")

            return {
                'train_mae': train_mae,
                'val_mae': val_mae,
                'val_r2': val_r2
            }

# FastAPI Production API
app = FastAPI(title="Real Estate Price Predictor", version="1.0.0")

# Prometheus metrics
PREDICTION_COUNTER = Counter('predictions_total', 'Total predictions made')
PREDICTION_LATENCY = Histogram('prediction_latency_seconds', 'Prediction latency')

class PropertyRequest(BaseModel):
    area: float
    bedrooms: int
    bathrooms: int
    age: int
    location: str
    property_type: str
    floor: int = 1
    facing: str = "East"

@app.post("/api/v1/predict")
@PREDICTION_LATENCY.time()
async def predict_price(request: PropertyRequest):
    """Production prediction endpoint"""
    try:
        PREDICTION_COUNTER.inc()

        # Validate input
        if request.area <= 0:
            raise HTTPException(status_code=400, detail="Area must be positive")

        # Prepare input
        input_data = pd.DataFrame([request.dict()])

        # Load and use model
        # Ensure the 'models' directory exists and the model file is present
        # For demonstration, a placeholder or pre-trained model loading needs to be handled.
        # In a real scenario, this would load a model registered with MLflow or a direct path.
        try:
            with open('models/production_model.pkl', 'rb') as f:
                model = pickle.load(f)
        except FileNotFoundError:
            raise HTTPException(status_code=500, detail="Model file not found. Ensure 'models/production_model.pkl' exists.")

        prediction = model.predict(input_data)[0]

        # Generate confidence interval
        margin = prediction * 0.1  # 10% margin

        return {
            "prediction_id": str(uuid.uuid4()),
            "timestamp": datetime.now().isoformat(),
            "predicted_price": round(prediction, 2),
            "currency": "INR",
            "confidence_interval": {
                "lower_bound": round(prediction - margin, 2),
                "upper_bound": round(prediction + margin, 2)
            },
            "model_version": "1.0.0",
            "metadata": {
                "area_sqft": request.area,
                "location": request.location,
                "property_type": request.property_type
            }
        }

    except Exception as e:
        # Log the error for internal debugging
        logging.error(f"Prediction error: {str(e)}")
        # Return a generic error to the user
        raise HTTPException(status_code=500, detail="Internal server error during prediction")